
import { useState } from "react";
import {
  Send,
  Sparkles,
  Clock,
  Database,
  CheckCircle,
  XCircle,
  Copy,
  FileText
} from "lucide-react";
import {
  evaluateQuestion,
  submitFeedback
} from "../services/api";
import "./Playground.css";

function Playground() {
  const [question, setQuestion] = useState("");
  const [loading, setLoading] = useState(false);
  const [results, setResults] = useState([]);
  const [chunks, setChunks] = useState([]);
  const [retrievalTime, setRetrievalTime] = useState(null);
  const [evaluationId, setEvaluationId] = useState("");
  const [feedback, setFeedback] = useState({});
  const [feedbackLoading, setFeedbackLoading] = useState({});
  const [error, setError] = useState("");

  const handleSubmit = async (event) => {
    event.preventDefault();

    if (!question.trim()) {
      return;
    }

    setLoading(true);
    setError("");
    setResults([]);
    setChunks([]);
    setFeedback({});
    setRetrievalTime(null);

    try {
      const data = await evaluateQuestion(question.trim());

      setEvaluationId(data.evaluation_id);
      setResults(data.results || []);
      setChunks(data.retrieved_chunks || []);
      setRetrievalTime(data.retrieval_time);
    } catch (error) {
      setError(
        error.response?.data?.detail ||
        "Unable to connect to the RAG backend. Check whether FastAPI is running."
      );
    } finally {
      setLoading(false);
    }
  };

  const handleFeedback = async (result, value) => {
    const modelId = result.model_id;

    setFeedbackLoading((previous) => ({
      ...previous,
      [modelId]: true
    }));

    try {
      await submitFeedback(evaluationId, modelId, value);

      setFeedback((previous) => ({
        ...previous,
        [modelId]: value
      }));
    } catch (error) {
      setError(
        error.response?.data?.detail ||
        "Unable to save feedback."
      );
    } finally {
      setFeedbackLoading((previous) => ({
        ...previous,
        [modelId]: false
      }));
    }
  };

  const copyAnswer = async (answer) => {
    try {
      await navigator.clipboard.writeText(answer);
    } catch {
      setError("Unable to copy the answer.");
    }
  };

  return (
    <div className="playground">
      <div className="playground-heading">
        <div>
          <p className="playground-eyebrow">AI WORKSPACE</p>
          <h1>RAG Playground</h1>
          <p>Ask questions and compare responses from multiple AI models.</p>
        </div>

        <div className="demo-label">
          <span></span>
          Live mode
        </div>
      </div>

      <div className="playground-layout">
        <section className="question-panel">
          <div className="section-title">
            <div className="playground-icon">
              <Sparkles size={20} />
            </div>
            <div>
              <h3>Ask your documents</h3>
              <p>Enter a question to start an evaluation.</p>
            </div>
          </div>

          <form onSubmit={handleSubmit}>
            <label htmlFor="question">Your question</label>

            <textarea
              id="question"
              value={question}
              onChange={(event) => setQuestion(event.target.value)}
              placeholder="Example: What is the main topic of the document?"
              rows={5}
            />

            <div className="question-footer">
              <span>{question.length} characters</span>

              <button
                type="submit"
                disabled={loading || !question.trim()}
              >
                {loading ? "Evaluating..." : "Run Evaluation"}
                <Send size={16} />
              </button>
            </div>
          </form>

          <div className="retrieval-info">
            <div>
              <Database size={17} />
              <span>Vector database</span>
              <strong>ChromaDB</strong>
            </div>

            <div>
              <FileText size={17} />
              <span>Retrieved chunks</span>
              <strong>{chunks.length || 3}</strong>
            </div>

            <div>
              <Sparkles size={17} />
              <span>Configured models</span>
              <strong>4</strong>
            </div>

            {retrievalTime !== null && (
              <div>
                <Clock size={17} />
                <span>Retrieval time</span>
                <strong>{retrievalTime}s</strong>
              </div>
            )}
          </div>
        </section>

        <section className="evaluation-panel">
          <div className="evaluation-heading">
            <div>
              <h3>Evaluation Results</h3>
              <p>Compare answers generated by each model.</p>
            </div>
            <span className="model-count">4 Models</span>
          </div>

          {error && (
            <div
              style={{
                background: "#3a202e",
                border: "1px solid #824451",
                color: "#ff9aaa",
                padding: "12px",
                borderRadius: "8px",
                fontSize: "11px",
                marginBottom: "15px"
              }}
            >
              {error}
            </div>
          )}

          {loading && (
            <div className="loading-state">
              <div className="loader"></div>
              <h3>Preparing evaluation</h3>
              <p>Retrieving document chunks and contacting AI models...</p>
            </div>
          )}

          {!loading && results.length === 0 && (
            <div className="empty-state">
              <div className="empty-icon">
                <Sparkles size={27} />
              </div>
              <h3>Ready when you are</h3>
              <p>
                Enter a question above to compare responses generated
                using your actual document context.
              </p>
            </div>
          )}

          {!loading && results.length > 0 && (
            <div className="results-list">
              {results.map((result, index) => (
                <article className="result-card" key={result.model_id}>
                  <div className="result-card-header">
                    <div className="result-model">
                      <div className="result-model-number">
                        {index + 1}
                      </div>

                      <div>
                        <h4>{result.model_name}</h4>
                        <p>{result.model_id}</p>
                      </div>
                    </div>

                    <button
                      className="copy-button"
                      type="button"
                      onClick={() => copyAnswer(result.answer)}
                      title="Copy answer"
                      disabled={!result.answer}
                    >
                      <Copy size={16} />
                    </button>
                  </div>

                  <div className="answer-content">
                    <span className="answer-label">AI RESPONSE</span>
                    <p>
                      {result.status === "Success"
                        ? result.answer
                        : result.error || "The model could not generate an answer."}
                    </p>
                  </div>

                  <div className="result-metrics">
                    <div>
                      <Clock size={15} />
                      <span>{result.response_time}s</span>
                    </div>

                    <div>
                      <Database size={15} />
                      <span>{chunks.length} source chunks</span>
                    </div>

                    <div>
                      <span>{result.status}</span>
                    </div>
                  </div>

                  {result.status === "Success" && (
                    <div className="feedback-area">
                      <span>Was this answer correct?</span>

                      <button
                        type="button"
                        disabled={feedbackLoading[result.model_id]}
                        className={
                          feedback[result.model_id] === "Correct"
                            ? "selected-good"
                            : ""
                        }
                        onClick={() => handleFeedback(result, "Correct")}
                      >
                        <CheckCircle size={15} />
                        Correct
                      </button>

                      <button
                        type="button"
                        disabled={feedbackLoading[result.model_id]}
                        className={
                          feedback[result.model_id] === "Incorrect"
                            ? "selected-bad"
                            : ""
                        }
                        onClick={() => handleFeedback(result, "Incorrect")}
                      >
                        <XCircle size={15} />
                        Incorrect
                      </button>

                      {feedbackLoading[result.model_id] && (
                        <span>Saving...</span>
                      )}

                      {feedback[result.model_id] && (
                        <span className="feedback-saved">
                          Feedback saved
                        </span>
                      )}
                    </div>
                  )}
                </article>
              ))}
            </div>
          )}
        </section>
      </div>

      {chunks.length > 0 && (
        <section className="panel" style={{ marginTop: "20px" }}>
          <div className="panel-header">
            <div>
              <h3>Retrieved Document Chunks</h3>
              <p>Context retrieved from your ChromaDB collection.</p>
            </div>
            <span className="model-count">{chunks.length} Sources</span>
          </div>

          <div className="results-list" style={{ marginTop: "18px" }}>
            {chunks.map((chunk) => (
              <article className="result-card" key={chunk.id}>
                <div className="result-card-header">
                  <h4>{chunk.id}</h4>
                  <span className="source-tag">
                    Distance: {Number(chunk.distance).toFixed(4)}
                  </span>
                </div>
                <div className="answer-content">
                  <p>{chunk.text}</p>
                </div>
              </article>
            ))}
          </div>
        </section>
      )}
    </div>
  );
}

export default Playground;
